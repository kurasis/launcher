// The interface text in the chosen language (D-038).
//
// Catalogs are ICU MessageFormat JSON files in src/locales/messages, one per
// language tag; English is the source and is always loaded, every other language
// is loaded when chosen. A text missing from a catalog comes from the next
// language in the chain `pt-BR` → `pt` → `en`. Components import `strings` and
// read it while rendering: a text without values is a string, a text with values
// is a function of them. References taken earlier (`const t = strings.settings`)
// always resolve to the current language.
import { TYPE } from '@formatjs/icu-messageformat-parser';
import { IntlMessageFormat } from 'intl-messageformat';
import languageList from '../locales/languages.json';
import english from '../locales/messages/en.json';
import type { ErrorCode } from './contracts';
import type { Messages } from './i18n/messages';

export type { Messages };

/** Sections of the Settings screen. */
export type SettingsSection =
  'general' | 'java' | 'defaults' | 'network' | 'installations' | 'privacy' | 'reset';

type Tree = { readonly [key: string]: string | Tree };

interface Catalog {
  readonly _meta: {
    readonly name: string;
    readonly dir: string;
    /** Unicode numbering system for formatted numbers, e.g. `latn`. */
    readonly numbering?: string;
  };
  readonly ui: Tree;
  readonly errors: Readonly<Record<string, string>>;
}

export interface LanguageInfo {
  readonly tag: string;
  /** The language's name in itself. */
  readonly name: string;
  readonly dir: string;
  /** Share of English texts this catalog translates, 0–100. */
  readonly translated: number;
}

/** Every language with a catalog (generated by scripts/i18n.mjs). */
export const LANGUAGES: readonly LanguageInfo[] = languageList;

const ENGLISH = 'en';
const source: Catalog = english;
const loaders = import.meta.glob<Catalog>(
  ['../locales/messages/*.json', '!../locales/messages/en.json'],
  { import: 'default' },
);
const loaded = new Map<string, Catalog>([[ENGLISH, source]]);

function loaderFor(tag: string) {
  return loaders[`../locales/messages/${tag}.json`];
}

function hasCatalog(tag: string): boolean {
  return tag === ENGLISH || loaderFor(tag) !== undefined;
}

/** `pt-BR` → [`pt-BR`, `pt`], keeping only languages that exist. */
function candidates(tag: string): string[] {
  const base = tag.split('-')[0] ?? tag;
  return [...new Set([tag, base])].filter(hasCatalog);
}

/**
 * Loads the catalogs `tag` needs and returns the tag the interface will use:
 * `tag` itself, its base language, or English.
 */
export async function loadLanguage(tag: string): Promise<string> {
  const found = candidates(tag);
  for (const candidate of found) {
    const load = loaderFor(candidate);
    if (!loaded.has(candidate) && load !== undefined) loaded.set(candidate, await load());
  }
  return found[0] ?? ENGLISH;
}

let current = ENGLISH;
let chain: (readonly [string, Catalog])[] = [[ENGLISH, source]];

export function language(): string {
  return current;
}

export function direction(): 'ltr' | 'rtl' {
  return chain[0]?.[1]._meta.dir === 'rtl' ? 'rtl' : 'ltr';
}

function localeOf(tag: string, catalog: Catalog): string {
  const numbering = catalog._meta.numbering;
  return numbering === undefined ? tag : `${tag}-u-nu-${numbering}`;
}

/** The locale numbers and dates are formatted with, e.g. `ar-u-nu-latn`. */
export function numberLocale(): string {
  const [tag, catalog] = chain[0] ?? [ENGLISH, source];
  return localeOf(tag, catalog);
}

/** Mirrors the setting for the first paint and for the console window. */
export const LANGUAGE_STORAGE_KEY = 'launcher.language';

export function storedLanguage(): string {
  try {
    return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) ?? ENGLISH;
  } catch {
    return ENGLISH;
  }
}

const formatters = new Map<string, IntlMessageFormat>();
/** Texts without values, per path, in the current language. */
const formatted = new Map<string, string>();

/** Switches to a loaded language (see `loadLanguage`); the caller re-renders. */
export function setLanguage(tag: string): void {
  const usable = candidates(tag).filter((t) => loaded.has(t));
  current = usable[0] ?? ENGLISH;
  chain = [...new Set([...usable, ENGLISH])].map((t) => [t, loaded.get(t) ?? source] as const);
  formatted.clear();
  document.documentElement.lang = current;
  document.documentElement.dir = direction();
  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, current);
  } catch {
    // Storage is optional; the setting in the core stays authoritative.
  }
}

// ---------------------------------------------------------------- formatting

function formatter(locale: string, message: string): IntlMessageFormat {
  const key = `${locale}\u0000${message}`;
  let cached = formatters.get(key);
  if (cached === undefined) {
    cached = new IntlMessageFormat(message, locale);
    formatters.set(key, cached);
  }
  return cached;
}

type Values = Record<string, string | number | boolean>;

function render(tag: string, catalog: Catalog, message: string, values?: Values): string {
  const result = formatter(localeOf(tag, catalog), message).format(values);
  return Array.isArray(result) ? result.join('') : String(result);
}

function at(tree: Tree, path: readonly string[]): string | Tree | undefined {
  let value: string | Tree | undefined = tree;
  for (const key of path) {
    if (value === undefined || typeof value === 'string') return undefined;
    value = value[key];
  }
  return value;
}

/** The text at `path` from the first language in the chain that has it. */
function text(path: readonly string[], values?: Values): string {
  for (const [tag, catalog] of chain) {
    const message = at(catalog.ui, path);
    if (typeof message === 'string') return render(tag, catalog, message, values);
  }
  return path.join('.');
}

const takesValues = new Map<string, boolean>();

/** Whether the English text shows values (and so is a function of them). */
function hasValues(id: string, message: string): boolean {
  let result = takesValues.get(id);
  if (result === undefined) {
    result = formatter(ENGLISH, message)
      .getAst()
      .some((element) => element.type !== TYPE.literal);
    takesValues.set(id, result);
  }
  return result;
}

const views = new Map<string, object>();

function view(path: readonly string[]): object {
  const id = path.join('.');
  const cached = views.get(id);
  if (cached !== undefined) return cached;
  const node = (key: string) => at(source.ui, [...path, key]);
  const read = (key: string): unknown => {
    const message = node(key);
    const childPath = [...path, key];
    if (message === undefined) return undefined;
    if (typeof message !== 'string') return view(childPath);
    const childId = childPath.join('.');
    if (hasValues(childId, message)) return (values: Values) => text(childPath, values);
    let value = formatted.get(childId);
    if (value === undefined) {
      value = text(childPath);
      formatted.set(childId, value);
    }
    return value;
  };
  const proxy = new Proxy(
    {},
    {
      get: (_target, key) => (typeof key === 'string' ? read(key) : undefined),
      has: (_target, key) => typeof key === 'string' && node(key) !== undefined,
      ownKeys: () => {
        const tree = at(source.ui, path);
        return tree !== undefined && typeof tree !== 'string' ? Object.keys(tree) : [];
      },
      getOwnPropertyDescriptor: (_target, key) =>
        typeof key === 'string' && node(key) !== undefined
          ? { configurable: true, enumerable: true, value: read(key) }
          : undefined,
    },
  );
  views.set(id, proxy);
  return proxy;
}

export const strings = view([]) as Messages;

// ---------------------------------------------------------------- core messages

/** A text from the Rust core: English `message`, and its template and values. */
export interface CoreText {
  code?: ErrorCode;
  message: string;
  template?: string;
  params?: Readonly<Record<string, string | number | boolean>>;
}

/** A value that is itself a core text, such as "Saving settings", is translated. */
function translateValue(value: string | number | boolean): string | number | boolean {
  if (typeof value !== 'string') return value;
  for (const [tag, catalog] of chain) {
    if (tag === ENGLISH) break;
    const message = catalog.errors[value];
    if (message !== undefined) return render(tag, catalog, message);
  }
  return value;
}

/**
 * A core message in the current language: its translation, else (for a message
 * no catalog knows) a sentence for its code, else the English text.
 */
export function localizeError(error: CoreText): string {
  if (current === ENGLISH) return error.message;
  const key = error.template ?? error.message;
  const values: Values = {};
  for (const [name, value] of Object.entries(error.params ?? {})) {
    values[name] = translateValue(value);
  }
  for (const [tag, catalog] of chain) {
    if (tag === ENGLISH) break;
    const message = catalog.errors[key];
    if (message !== undefined) return render(tag, catalog, message, values);
  }
  if (!(key in source.errors) && error.code !== undefined) {
    return strings.errorCodes[error.code];
  }
  return error.message;
}
